class FakeRunner:
    def __init__(self, outputs: dict[str, Any]) -> None:
        self.outputs = outputs
        self.calls: list[tuple[list[str], Path]] = []

    def __call__(self, cmd: Sequence[str], cwd: Path) -> Any:
        cmd = list(cmd)
        self.calls.append((cmd, cwd))
        if cmd[:2] == ["uv", "export"]:
            key = "export_all" if "--all-groups" in cmd else "export_runtime"
        elif cmd[0] == "uvx":
            reqs = Path(cmd[cmd.index("-r") + 1])
            self.outputs["requirements"] = reqs.read_text(encoding="utf-8")
            key = "pip"
        else:
            key = cmd[0]
        value = self.outputs[key]
        if isinstance(value, sa.Result):
            return value
        text = value if isinstance(value, str) else json.dumps(value)
        return sa.Result(0, text)


def _repo(tmp_path: Path, lock: dict[str, Any] | None = None) -> Path:
    frontend = tmp_path / "src" / "frontend"
    frontend.mkdir(parents=True)
    (frontend / "package-lock.json").write_text(json.dumps(lock or LOCK), encoding="utf-8")
    return tmp_path


def _outputs(pip: Any = PIP_CLEAN, npm: Any = NPM_CLEAN) -> dict[str, Any]:
    return {
        "export_all": EXPORT_ALL,
        "export_runtime": EXPORT_RUNTIME,
        "pip": pip,
        "npm": npm,
        "git": "abc1234\n",
    }


def test_parse_requirements_skips_comments_and_markers() -> None:
    assert sa.parse_requirements(EXPORT_ALL) == {
        "colorama": "0.4.6",
        "fastapi": "0.162.0",
        "jinja2": "2.10",
        "ruff": "0.17.4",
    }


def test_lock_packages_dedupes_and_prefers_runtime() -> None:
    packages = {(p.name, p.version): p.kind for p in sa.lock_packages(LOCK)}
    assert packages == {
        ("@scope/pkg", "2.0.0"): "dev",
        ("minimist", "1.2.0"): "runtime",
        ("react", "19.3.1"): "runtime",
    }


def test_clean_run_writes_report_and_exits_zero(tmp_path: Path) -> None:
    root = _repo(tmp_path)
    out = tmp_path / "report.md"
    runner = FakeRunner(_outputs())
    assert sa.main(["--root", str(root), "--output", str(out)], runner=runner) == 0
    report = out.read_text(encoding="utf-8")
    assert "**No known vulnerabilities found.**" in report
    assert "`abc1234`" in report
    assert "| fastapi | 0.162.0 | runtime | clean |" in report
    assert "| ruff | 0.17.4 | dev | clean |" in report
    assert "| react | 19.3.1 | runtime | clean |" in report
    # Exact pins, no environment markers, are passed to pip-audit.
    assert runner.outputs["requirements"].splitlines() == [
        "colorama==0.4.6",
        "fastapi==0.162.0",
        "jinja2==2.10",
        "ruff==0.17.4",
    ]
    npm_call = next(c for c in runner.calls if c[0][0] == "npm")
    frontend = root / "src" / "frontend"
    assert npm_call == (["npm", "audit", "--json", "--package-lock-only"], frontend)


def test_findings_are_reported_and_exit_one(tmp_path: Path) -> None:
    root = _repo(tmp_path)
    out = tmp_path / "report.md"
    outputs = _outputs(pip=PIP_VULN, npm=NPM_VULN)
    # Both tools exit 1 when they find something.
    outputs["pip"] = sa.Result(1, json.dumps(PIP_VULN))
    outputs["npm"] = sa.Result(1, json.dumps(NPM_VULN))
    assert sa.main(["--root", str(root), "-o", str(out)], runner=FakeRunner(outputs)) == 1
    report = out.read_text(encoding="utf-8")
    assert "**3 advisory finding(s).**" in report
    assert (
        "| jinja2 | 2.10 | runtime | PYSEC-2021-66, GHSA-g3rq-g295-4j3m, CVE-2020-28493 "
        "| not reported | 2.11.3 | ReDoS in the urlize filter \\| with a pipe. |"
    ) in report
    assert (
        "| minimist | 1.2.0 | runtime "
        "| [GHSA-xvch-5gv4-984h](https://github.com/advisories/GHSA-xvch-5gv4-984h) "
        "| critical | minimist@1.2.8 | Prototype Pollution in minimist |"
    ) in report
    assert (
        "| @scope/pkg | 2.0.0 | dev | via minimist | critical | yes (`npm audit fix`) |"
    ) in report
    assert "| jinja2 | 2.10 | runtime | advisory |" in report
    assert "| ruff | 0.17.4 | dev | clean |" in report


@pytest.mark.parametrize("broken", ["pip", "npm", "export_all"])
def test_tool_failure_is_recorded_and_exits_two(tmp_path: Path, broken: str) -> None:
    root = _repo(tmp_path)
    out = tmp_path / "report.md"
    outputs = _outputs()
    outputs[broken] = sa.Result(2, "", "network unreachable")
    assert sa.main(["--root", str(root), "-o", str(out)], runner=FakeRunner(outputs)) == 2
    report = out.read_text(encoding="utf-8")
    assert "**Incomplete:**" in report
    assert "network unreachable" in report


def test_npm_error_json_is_a_failure(tmp_path: Path) -> None:
    root = _repo(tmp_path)
    outputs = _outputs(npm={"error": {"code": "ENOLOCK", "summary": "no lockfile"}})
    out = tmp_path / "report.md"
    assert sa.main(["--root", str(root), "-o", str(out)], runner=FakeRunner(outputs)) == 2
    assert "ENOLOCK" in out.read_text(encoding="utf-8")


def test_missing_lockfile_is_a_failure(tmp_path: Path) -> None:
    out = tmp_path / "report.md"
    assert sa.main(["--root", str(tmp_path), "-o", str(out)], runner=FakeRunner(_outputs())) == 2
    assert "cannot read package-lock.json" in out.read_text(encoding="utf-8")


